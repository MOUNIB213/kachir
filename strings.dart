String tr(String key, String lang) => _t[lang]?[key] ?? _t['en']![key] ?? key;

extension Tr on BuildContext {
  /// لا يستمع للتغييرات؛ تتم إعادة بناء الشجرة كاملة عند تغيير اللغة.
  String t(String key) =>
      tr(key, Provider.of<AppState>(this, listen: false).lang);
}

final _nf = NumberFormat('#,##0.00', 'en');

String money(double v, String lang) => '${_nf.format(v)} ${tr('currency', lang)}';

String qtyStr(double v) =>
    v == v.roundToDouble() ? v.toStringAsFixed(0) : v.toStringAsFixed(2);
